function buildQuestion(category: string, row: Row, index: number): SeedQuestion {
  const [text, correct, ...wrong] = row;
  const correctIndex = (index + 1) % 4;
  const options = [...wrong];
  options.splice(correctIndex, 0, correct);
  return { category, text, options, correctIndex };
}

export const ADVANCED2_QUESTIONS: SeedQuestion[] = Object.entries(groups).flatMap(
  ([category, rows]) => rows.map((row, index) => buildQuestion(category, row, index))
);
